# -*- coding: utf-8 -*-
import streamlit as st

from src import config as C
from src import data as D
from src.ui import header

header("🏙️ 서울 행정동 상권 기회 대시보드",
       "서울 25개 자치구 · 425개 행정동 · 기준 2025년 (추세 2023Q1–2025Q4) · 인구·인프라 기반 기대소비 모델 + 상권 키워드")

df = D.dong(("행정동_코드", "배율", "기회_유형", "잔차_추세_pct", "해석주의_여부"))
ok = df[df["기회_유형"] != "데이터점검"]

c = st.columns(5)
c[0].metric("행정동", f"{len(df):,}개")
c[1].metric("배율 중앙값", f"×{ok['배율'].median():.2f}", help="실제 소비 ÷ 인구·인프라로 예측한 기대 소비")
c[2].metric("① 선점형 기회", f"{(df['기회_유형'] == C.OPP_ORDER[0]).sum()}개 동",
            help="기대 미만인데 격차가 줄어드는 중")
c[3].metric("② 유출보완형 기회", f"{(df['기회_유형'] == C.OPP_ORDER[1]).sum()}개 동",
            help="기대 미만이 꾸준히 유지 — 소비가 동네 밖으로 샘")
c[4].metric("⑤·⑥ 둔화·위축", f"{df['기회_유형'].isin(C.OPP_ORDER[4:]).sum()}개 동")

st.divider()
left, right = st.columns([1.1, 1])
with left:
    st.subheader("이 대시보드로 할 수 있는 것")
    st.markdown("""
| 메뉴 | 내용 |
|---|---|
| 📋 **데이터 개요** | 컬럼 사전 · 결측 · 기술통계 |
| 📊 **분포 분석** | 기회 유형 · 금융MBTI · 상권 원형 · 태그 · 업종 공백 분포 |
| 🔗 **관계 분석** | 교차표 · 상관 · 청년비율과 소비 추세 · 수준×추세 사분면 |
| 🏙️ **자치구 비교** | 25개 구 배율 · 기회 구성 · 지표 순위 |
| 🗺️ **상권 지도** | 서울 전체(자치구) → 선택 자치구 행정동 지도 (folium) |
| 🎯 **기회 탐색** | 조건 필터 · 순위 · CSV 내려받기 |
| 🔍 **행정동 상세** | 한 동의 키워드 · 업종 · 모델 결과 프로필 |
""")
with right:
    st.subheader("핵심 발견")
    st.markdown("""
1. **청년 비율이 높은 동일수록 소비가 식는 중** — 청년비율 × 잔차 추세 ρ = −0.45
2. **금융MBTI가 상권 흐름을 가른다** — 영앤레버리지형 58%가 둔화·위축, 자산안정형 43%가 선점·확장
3. **가족·아파트단지형의 46%가 유출보완형** — 대단지 소비가 밖으로 샘 (생활용품·의료 공백)
4. **배율 ×5↑ / ×0.25↓ 22개 동은 집계 착시 가능성** — `해석주의`로 분리해 해석
""")
    with st.expander("용어"):
        st.markdown("""
- **배율** = 실제 소비 ÷ 기대 소비. ×1 이면 인구·인프라 수준만큼 쓰는 동네
- **잔차 추세** = 기대 대비 격차의 연간 변화 (+ 면 개선)
- **기회 유형** = 배율 수준(저평가·기대·초과) × 추세(개선·안정·악화) 조합
""")
        for k, v in C.OPP_DESC.items():
            st.markdown(f"- **{k}** — {v}")

st.caption("데이터: 서울시 상권분석서비스, SKT 시민생활 데이터, apt.wiki 키워드 · 경계: 행정안전부 행정동 경계 (vuski/admdongkor) "
           "· 지도 타일: © Esri · © OpenStreetMap contributors")
